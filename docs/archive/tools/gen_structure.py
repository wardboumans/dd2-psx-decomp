"""Generate sourcecode/STRUCTURE.md from function_map.json.

Usage: python gen_structure.py <mapping dir> <out.md>

Consecutive functions (in address order, per code block) that map to the same
source file form one module row. An unmapped function between two functions
of the same file is counted in that file's row; other unmapped runs get their
own "?" row so they stay visible.
"""
import json
import os
import sys

BLOCKS = [
    ("EXE", "SCUS_943.50 (main executable)"),
    ("FRONTEND", "FRONTEND.BIN (overlay at 0x801C4000)"),
    ("GENERAL", "GENERAL.BIN (overlay at 0x801E0000)"),
    ("RESULTS", "RESULTS.BIN (overlay at 0x801C4000, Ghidra block ov1)"),
]


def block_of(address):
    if address.startswith("ov1::"):
        return "RESULTS"
    v = int(address, 16)
    if 0x800116EC <= v < 0x8005E5EC:
        return "EXE"
    if 0x801C4000 <= v < 0x801E0000:
        return "FRONTEND"
    if 0x801E0000 <= v < 0x801F3000:
        return "GENERAL"
    return None


def map_key(address, block):
    a = address.split("::")[-1]
    return a if block == "EXE" else f"{block}:{a}"


def status(entry):
    if entry is None:
        return "unmapped"
    if entry["evidence"] in ("manual", "graph-checked") or entry["status"] != "mapped":
        return "checked"
    return entry["confidence"]


def main():
    mapping, out_path = sys.argv[1], sys.argv[2]
    fmap = json.load(open(os.path.join(mapping, "function_map.json")))
    funcs = json.load(open(os.path.join(mapping, "psx_functions.json")))
    lines = [
        "# PSX module map",
        "",
        "Generated by `tools/gen_structure.py` from `mapping/function_map.json`; do not edit by hand,",
        "fix the map and regenerate. Address ranges are PSX addresses; each row is a run of",
        "consecutive functions that map to the same source file. Counts: checked (by hand or",
        "call graph) / high confidence / low confidence / unmapped. Low and unmapped functions",
        "must be verified when their module is written (see CLAUDE.md).",
        "",
    ]
    totals = {"checked": 0, "high": 0, "low": 0, "unmapped": 0}
    for block, title in BLOCKS:
        seq = sorted((f for f in funcs if block_of(f["address"]) == block),
                     key=lambda f: int(f["address"].split("::")[-1], 16))
        recs = []
        for f in seq:
            e = fmap.get(map_key(f["address"], block))
            recs.append({"addr": f["address"].split("::")[-1], "end": int(f["address"].split("::")[-1], 16) + f["size"],
                         "file": e["file"] if e else None, "status": status(e)})
        # unmapped functions between two of the same file belong to that file
        for i, r in enumerate(recs):
            if r["file"] is None:
                prev = next((x["file"] for x in reversed(recs[:i]) if x["file"]), None)
                nxt = next((x["file"] for x in recs[i + 1:] if x["file"]), None)
                r["file"] = prev if prev and prev == nxt else "?"
        rows = []
        for r in recs:
            if rows and rows[-1]["file"] == r["file"]:
                rows[-1]["end"] = r["end"]
                rows[-1]["counts"][r["status"]] += 1
            else:
                counts = {"checked": 0, "high": 0, "low": 0, "unmapped": 0}
                counts[r["status"]] += 1
                rows.append({"start": r["addr"], "end": r["end"], "file": r["file"], "counts": counts})
            totals[r["status"]] += 1
        lines += [f"## {title}", "", "| Range | File | Functions | checked / high / low / unmapped |", "|---|---|---|---|"]
        for row in rows:
            c = row["counts"]
            lines.append(f"| `{row['start']}-{row['end'] - 1:08x}` | `{row['file']}` | {sum(c.values())} "
                         f"| {c['checked']} / {c['high']} / {c['low']} / {c['unmapped']} |")
        lines.append("")
    lines.insert(8, f"Totals: {totals['checked']} checked, {totals['high']} high, {totals['low']} low, "
                    f"{totals['unmapped']} unmapped.\n")
    with open(out_path, "w") as fh:
        fh.write("\n".join(lines))
    print(totals)


if __name__ == "__main__":
    main()
